"""Split criterion test, general n.  For D (ascent-type simple), supp(D)={mu : M_mu x_D != 0}.
Edge mu->nu if some S-map phi_w (w in M_nu, Asc(w) in S(mu)) has phi_w(M_mu x_D) != 0.
>=2 components  =>  A != B (Lemma Split).  Exact over Q (integer vectors, flint rank)."""
import sys, itertools
from collections import defaultdict
from flint import fmpz_mat
def asc(w): return frozenset(i+1 for i in range(len(w)-1) if w[i]<w[i+1])
def move(w,i):  # right action of pi_i (i 1-based): swap if ascent
    if w[i-1]<w[i]: return w[:i-1]+(w[i],w[i-1])+w[i+1:]
    return w
def act_pi(vec,i):
    out=defaultdict(int)
    for w,c in vec.items(): out[move(w,i)]+=c
    return {w:c for w,c in out.items() if c}
def act_pibar(vec,i):
    out=defaultdict(int)
    for w,c in vec.items():
        out[w]+=c; out[move(w,i)]-=c
    return {w:c for w,c in out.items() if c}
def w0word(J):
    # reduced word of longest element of parabolic generated by J (1-based gens): per consecutive block
    J=sorted(J); blocks=[]; 
    for j in J:
        if blocks and blocks[-1][-1]==j-1: blocks[-1].append(j)
        else: blocks.append([j])
    word=[]
    for b in blocks:
        a=b[0]; m=len(b)
        for r in range(m):          # w0 of S_{m+1} on gens a..a+m-1: (a..a+m-1)(a..a+m-2)...(a)
            word+=list(range(a,a+m-r))
    return word
def xD(vec,D,N):
    Dc=[j for j in range(1,N) if j not in D]
    for i in w0word(D): vec=act_pibar(vec,i)
    for i in w0word(Dc): vec=act_pi(vec,i)
    return vec
def rank(vecs,basis):
    if not vecs: return 0
    idx={b:k for k,b in enumerate(basis)}
    return fmpz_mat([[v.get(b,0) for b in basis] for v in vecs]).rank()
def run(n,N,Ds=None,verbose=False):
    W=list(itertools.product(range(1,n+1),repeat=N))
    wts=defaultdict(list)
    for w in W: wts[tuple(w.count(c) for c in range(1,n+1))].append(w)
    # path from v0 to each word: v = v0 . pi_{i1} ... pi_{ik}
    path={}
    for mu,ws in wts.items():
        v0=tuple(c for c in range(1,n+1) for _ in range(mu[c-1]))
        P={v0:()}; fr=[v0]
        while fr:
            nf=[]
            for v in fr:
                for i in range(1,N):
                    u=move(v,i)
                    if u not in P: P[u]=P[v]+(i,); nf.append(u)
            fr=nf
        assert len(P)==len(ws); path[mu]=(v0,P)
    def Smaps(mu,nu):
        v0,_=path[mu]; S=asc(v0)
        return [w for w in wts[nu] if asc(w)<=S]
    def phi(w,mu,vec):
        _,P=path[mu]; out=defaultdict(int)
        for v,c in vec.items():
            u=w
            for i in P[v]: u=move(u,i)
            out[u]+=c
        return {x:c for x,c in out.items() if c}
    if Ds is None:
        Ds=sorted({asc(w) for w in W},key=lambda s:(len(s),sorted(s)))
    res={}
    for D in Ds:
        D=frozenset(D)
        imgs={}
        for mu,ws in wts.items():
            vs=[xD({w:1},D,N) for w in ws]; vs=[v for v in vs if v]
            if vs and rank(vs,ws)>0: imgs[mu]=vs
        supp=list(imgs)
        adj={mu:set() for mu in supp}
        for mu in supp:
            for nu in supp:
                if mu==nu: continue
                for w in Smaps(mu,nu):
                    if any(phi(w,mu,v) for v in imgs[mu]):
                        adj[mu].add(nu); adj[nu].add(mu); break
        # components
        comp=[]; seen=set()
        for mu in supp:
            if mu in seen: continue
            st=[mu]; c=set()
            while st:
                x=st.pop()
                if x in c: continue
                c.add(x); st+=list(adj[x])
            seen|=c; comp.append(sorted(c))
        res[tuple(sorted(D))]=comp
        if len(comp)>=2 or verbose:
            print(n,N,'D',sorted(D),'supp',len(supp),'components',len(comp),comp if len(comp)<6 else '',flush=True)
    return res
if __name__=='__main__':
    n,N=map(int,sys.argv[1:3])
    r=run(n,N)
    print(n,N,'done; split D count',sum(1 for c in r.values() if len(c)>=2),'of',len(r))
