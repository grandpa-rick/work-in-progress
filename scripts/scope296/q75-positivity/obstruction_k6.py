#!/usr/bin/env python3
"""k=6: list every positive partial chain B_0..B_7 of Schur-subset bases, and for each chain and each of the
Schur bases B_8 a witness product s_lam*s_mu (lam in B_i, mu in B_{8-i}) with a negative coefficient.
Then look for a chain-uniform certificate.  Grade: computed."""
from collections import Counter
from engine import *
from positivity import setup, bases_in_degree
k = 6
d, g, nz, r = setup(k)
print('nonzero counts', [len(nz[n]) for n in range(d + 1)], 'r', [r[n] for n in range(d + 1)])
choices = {n: bases_in_degree(g, nz, r, n) for n in range(9)}
def coef(Bn, n, lam, mu):
    return solve([g.img(l) for l in Bn], g.img_of(lr(lam, mu), n))
chains = []
def rec(n, B):
    if n == 8: chains.append(dict(B)); return
    for S in choices[n]:
        if all(min(coef(S, n, l, m)) >= 0 for i in range(1, n // 2 + 1) for l in B[i] for m in B[n - i]):
            B[n] = S; rec(n + 1, B); del B[n]
rec(0, {})
print('#positive chains through degree 7:', len(chains))
for c in chains: print('  ', {n: c[n] for n in range(2, 8)})
# products available into degree 8 for each chain
for c in chains:
    prods = [(l, m) for i in range(1, 5) for l in c[i] for m in c[8 - i]]
    print('chain', {n: c[n] for n in (5, 6, 7)}, '#products into deg 8:', len(prods))
    # cone generated by these products' images must lie in cone(B_8); check which B_8 fail and why
    wit = Counter()
    for S in choices[8]:
        bad = None
        for (l, m) in prods:
            x = coef(S, 8, l, m)
            if min(x) < 0: bad = (l, m, S, [str(t) for t in x]); break
        assert bad is not None
        wit[(bad[0], bad[1])] += 1
    print('   first-failing product histogram:', dict(wit))
